def training_worker(params):
    try:
        g_state["training"] = True
        add_log("="*60)
        add_log("开始训练...")
        data_dir = params.get('data_dir', 'sensor_data')
        csv_files = glob.glob(os.path.join(data_dir, '*.csv'))
        add_log(f"数据目录: {data_dir}, 找到 {len(csv_files)} 个CSV文件")
        
        if len(csv_files) == 0:
            add_log("❌ 没有找到CSV文件，请先采集数据")
            g_state["training"] = False
            return
        
        # 加载所有CSV（多个标签分文件存储，这里合并训练）
        all_dfs = []
        for f in csv_files:
            add_log(f"  加载 {os.path.basename(f)}")
            df = pd.read_csv(f)
            all_dfs.append(df)
        df = pd.concat(all_dfs, ignore_index=True)
        add_log(f"总共 {len(df)} 条原始样本")

        # 提取特征标签
        feature_cols = ['Odor', 'HCHO', 'CO', 'VOC', 'CO2']
        X_raw = df[feature_cols].values
        labels_raw = df['Label'].values
        unique_labels = sorted(list(set(labels_raw)))
        label_to_idx = {l:i for i,l in enumerate(unique_labels)}
        y_raw = np.array([label_to_idx[l] for l in labels_raw])

        add_log(f"\n类别列表 ({len(unique_labels)} 类):")
        for l,i in label_to_idx.items():
            add_log(f"  [{i}] {l}")

        # 滑动窗口
        ws = params['window_size']
        step = params['window_step']
        if ws > 1:
            X_window, y_window = create_sliding_windows(X_raw, y_raw, ws, step)
            add_log(f"\n滑动窗口: 大小={ws}, 步长={step}, 生成 {X_window.shape[0]} 样本")
        else:
            X_window = X_raw[:, np.newaxis, :]
            y_window = y_raw

        # 标准化
        n_features = X_window.shape[-1]
        scaler = StandardScaler()
        X_reshaped = X_window.reshape(-1, n_features)
        X_scaled_reshaped = scaler.fit_transform(X_reshaped)
        X = X_scaled_reshaped.reshape(X_window.shape)

        # 划分
        X_train, X_test, y_train, y_test = train_test_split(
            X, y_window, test_size=0.2, random_state=42, stratify=y_window
        )
        add_log(f"\n训练集: {X_train.shape[0]} 样本")
        add_log(f"测试集: {X_test.shape[0]} 样本")

        # 构建模型
        num_classes = len(unique_labels)
        model = build_model(X.shape[1:], num_classes, params['dropout'])
        model.compile(
            optimizer=tf.keras.optimizers.Adam(learning_rate=params['learning_rate']),
            loss='sparse_categorical_crossentropy',
            metrics=['accuracy']
        )

        early_stop = EarlyStopping(monitor='val_loss', patience=15, restore_best_weights=True)
        add_log("\n开始训练...")

        history = model.fit(
            X_train, y_train,
            batch_size=params['batch_size'],
            epochs=params['epochs'],
            validation_split=0.1,
            callbacks=[early_stop],
            verbose=0
        )

        test_loss, test_acc = model.evaluate(X_test, y_test, verbose=0)
        add_log(f"\n训练完成，测试准确率: {test_acc:.4f}")

        y_pred = model.predict(X_test, verbose=0)
        y_pred_classes = np.argmax(y_pred, axis=1)
        report = classification_report(y_test, y_pred_classes, target_names=unique_labels)
        add_log("\n分类报告:")
        for line in report.split('\n'):
            if line.strip():
                add_log(line)

        # 导出
        output_base = params['output_name']
        tflite_path = f"{output_base}.tflite"
        header_path = f"{output_base}.h"

        add_log(f"\n导出TFLite模型: {tflite_path}")
        tflite_model = convert_to_tflite(model, tflite_path)
        size_kb = len(tflite_model) / 1024
        add_log(f"模型大小: {size_kb:.1f} KB")

        add_log(f"导出C头文件: {header_path}")
        tflite_to_c_array(list(tflite_model), header_path)

        np.savez(f"{output_base}_params.npz", 
                mean=scaler.mean_, 
                std=np.sqrt(scaler.var_),
                classes=np.array(unique_labels, dtype=object))

        add_log(f"\n✅ 全部完成！")
        add_log(f"  {tflite_path} - INT8量化模型")
        add_log(f"  {header_path} - Arduino C头文件，直接include使用")
        add_log(f"  {output_base}_params.npz - 参数信息")

        g_state["last_result"] = {
            "accuracy": float(test_acc),
            "size_kb": float(size_kb),
            "header_path": header_path,
            "tflite_path": tflite_path
        }

    except Exception as e:
        add_log(f"❌ 训练出错: {str(e)}")
        import traceback
        for line in traceback.format_exc().split('\n'):
            if line.strip():
                add_log(line)
    finally:
        g_state["training"] = False

