@app.route('/api/ports')
def api_ports():
    ports = serial.tools.list_ports.comports()
    port_list = [p.device for p in ports]
    return jsonify({"ports": port_list})

@app.route('/api/connect', methods=['POST'])
def api_connect():
    data = request.get_json()
    port = data['port']
    baud = int(data['baud'])
    try:
        g_state["ser"] = serial.Serial(port, baud, timeout=1)
        add_log(f"✅ 成功连接 {port} @ {baud} baud")
        return jsonify({"success": True})
    except Exception as e:
        add_log(f"❌ 连接失败: {str(e)}")
        return jsonify({"success": False, "error": str(e)})

@app.route('/api/sync_interval', methods=['POST'])
def api_sync_interval():
    data = request.get_json()
    interval = int(data['interval'])
    if not g_state["ser"] or not g_state["ser"].is_open:
        add_log("❌ 串口未连接")
        return jsonify({"success": False, "error": "not connected"})
    cmd = f"set interval {interval}\n"
    g_state["ser"].write(cmd.encode())
    add_log(f"✅ 同步采集间隔: {interval} 秒")
    return jsonify({"success": True})

@app.route('/api/start_log', methods=['POST'])
def api_start_log():
    data = request.get_json()
    label = data['label']
    data_dir = data.get('data_dir', 'sensor_data')
    auto_stop_minutes = float(data.get('auto_stop_minutes', 0))
    interval = int(data.get('interval', 5))
    g_state["data_dir"] = data_dir
    if not g_state["ser"] or not g_state["ser"].is_open:
        add_log("❌ 串口未连接")
        return jsonify({"success": False, "error": "not connected"})
    if not label:
        add_log("❌ 标签为空")
        return jsonify({"success": False, "error": "empty label"})
    
    # 开始采集前清空串口输入缓冲区，避免残留旧数据一次性爆发读出
    g_state["ser"].reset_input_buffer()
    add_log("✅ 已清空串口输入缓冲区，避免残留旧数据")

    # 开始采集时只发送一次频率命令，避免频繁发送导致爆发
    if interval >= 2:
        cmd = f"set interval {interval}\n"
        g_state["ser"].write(cmd.encode())
        add_log(f"✅ 同步采集频率: {interval} 秒 → {cmd.strip()}")

    os.makedirs(data_dir, exist_ok=True)
    start_str = datetime.now().strftime('%Y%m%d_%H%M%S')
    filename = os.path.join(data_dir, f'{label}_{start_str}.csv')
    try:
        import csv
        g_state["csv_file"] = open(filename, 'w', newline='', encoding='utf-8-sig')
        g_state["csv_writer"] = csv.writer(g_state["csv_file"])
        header = ['Time_s', 'Odor', 'HCHO', 'CO', 'VOC', 'CO2', 'Label']
        g_state["csv_writer"].writerow(header)
        g_state["csv_file"].flush()
    except Exception as e:
        add_log(f"❌ 创建文件失败: {str(e)}")
        return jsonify({"success": False, "error": str(e)})
    
    g_state["current_label"] = label
    g_state["is_logging"] = True
    g_state["timer_seconds"] = int(auto_stop_minutes * 60) if auto_stop_minutes > 0 else 0
    g_state["timer_start_time"] = time.time()
    g_state["logging_thread"] = threading.Thread(target=logging_worker, daemon=True)
    g_state["logging_thread"].start()
    # 启动自动停止线程
    if auto_stop_minutes > 0:
        g_state["auto_stop_timer"] = threading.Thread(target=check_auto_stop, daemon=True)
        g_state["auto_stop_timer"].start()
        add_log(f"⏰ 自动停止设置: {auto_stop_minutes} 分钟，第一组数据到达后开始计时")
    add_log(f"✅ 开始采集，标签: {label}, 文件: {filename}（每个标签单独CSV）")
    return jsonify({"success": True})

