def create_sliding_windows(X, y, window_size, step):
    n_samples, n_features = X.shape
    windows = []
    labels = []
    for i in range(0, n_samples - window_size + 1, step):
        window = X[i:i+window_size, :]
        windows.append(window)
        center_idx = i + window_size // 2
        labels.append(y[center_idx])
    return np.array(windows), np.array(labels)

def build_model(input_shape, num_classes, dropout_rate):
    seq_len = input_shape[0]
    model = Sequential()
    model.add(Conv1D(16, kernel_size=3, activation='relu', input_shape=input_shape))
    model.add(BatchNormalization())
    if seq_len > 5:
        model.add(MaxPooling1D(pool_size=2))
    model.add(Dropout(dropout_rate))
    
    model.add(Conv1D(32, kernel_size=2, activation='relu'))
    model.add(BatchNormalization())
    if seq_len > 10:
        model.add(MaxPooling1D(pool_size=2))
    model.add(Dropout(dropout_rate))
    
    model.add(Flatten())
    model.add(Dense(16, activation='relu'))
    model.add(BatchNormalization())
    model.add(Dropout(dropout_rate))
    model.add(Dense(num_classes, activation='softmax'))
    return model

def convert_to_tflite(model, output_path):
    converter = tf.lite.TFLiteConverter.from_keras_model(model)
    converter.optimizations = [tf.lite.Optimize.DEFAULT]
    converter.target_spec.supported_ops = [tf.lite.OpsSet.TFLITE_BUILTINS_INT8]
    converter.inference_input_type = tf.int8
    converter.inference_output_type = tf.int8
    tflite_model = converter.convert()
    with open(output_path, 'wb') as f:
        f.write(tflite_model)
    return tflite_model

def tflite_to_c_array(tflite_model, output_header_path, array_name="g_food_freshness_model"):
    with open(output_header_path, 'w') as f:
        f.write("// Autogenerated by train_server.py\n");
        f.write("// DO NOT EDIT - generated from web training\n\n");
        f.write("#include <stddef.h>\n");
        f.write("#include <stdint.h>\n\n");
        f.write(f"const unsigned int {array_name}_size = {len(tflite_model)};\n");
        f.write(f"const unsigned char {array_name}[] = {{\n  ");
        bytes_per_line = 16;
        for i, byte in enumerate(tflite_model):
            f.write(f"0x{byte:02x}, ");
            if (i + 1) % bytes_per_line == 0:
                f.write("\n  ");
        if len(tflite_model) % bytes_per_line != 0:
            f.write("\n");
        f.write("};\n\n");
    return output_header_path

