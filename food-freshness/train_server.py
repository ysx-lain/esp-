def parse_block(lines):
    import re
    def extract(pattern):
        for line in lines:
            match = re.search(pattern, line)
            if match:
                return match.group(1).strip()
        return None

    odor = extract(r"Odor:\s+([\d\.]+)\s+ppm")
    hcho = extract(r"HCHO:\s+([\d\.]+)\s+ppm")
    co = extract(r"CO:\s+([\d\.]+)\s+ppm")
    voc = extract(r"VOC:\s+([\d\.]+)\s+ppm")
    co2 = extract(r"CO2:\s+(\d+)\s+ppm")
    timestamp = extract(r"发送端时间戳:\s+(\d+)\s+ms")

    if None in [odor, hcho, co, voc, co2, timestamp]:
        return None

    try:
        return [
            int(timestamp)//1000,
            float(odor),
            float(hcho),
            float(co),
            float(voc),
            int(co2),
            g_state["current_label"]
        ]
    except:
        return None

def check_auto_stop():
    """自动停止定时器"""
    while g_state["is_logging"] and g_state["timer_seconds"] > 0:
        if not g_state["is_logging"]:
            break  # 已经手动停止，直接退出
        elapsed = int(time.time() - g_state["timer_start_time"])
        remaining = g_state["timer_seconds"] - elapsed
        if remaining <= 0:
            add_log(f"⏰ 定时采集到时间，自动停止")
            g_state["is_logging"] = False
            if g_state["csv_file"]:
                g_state["csv_file"].close()
                g_state["csv_file"] = None
                g_state["csv_writer"] = None
            break
        time.sleep(1)
    if g_state["is_logging"] and g_state["csv_file"]:
        try:
            g_state["csv_file"].close()
        except:
            pass
        g_state["csv_file"] = None
        g_state["csv_writer"] = None

def logging_worker():
    block_lines = []
    inside_block = False
    first_block = True
    while g_state["is_logging"] and g_state["ser"] and g_state["ser"].is_open:
        try:
            raw = g_state["ser"].readline().decode('utf-8', errors='ignore').rstrip('\r\n')
            if not raw:
                continue
            add_log(f"📟 RAW: {raw}")

            if raw.startswith("========== 接收到传感器数据 =========="):
                block_lines = []
                inside_block = True
                if first_block:
                    add_log("✅ 收到第一组数据，开始计时")
                    g_state["timer_start_time"] = time.time()
                    first_block = False
                continue
            elif raw.startswith("======================================") and inside_block:
                record = parse_block(block_lines)
                if record and g_state["csv_writer"]:
                    g_state["csv_writer"].writerow(record)
                    g_state["csv_file"].flush()
                    if record:
                        add_log(f"记录样本: Odor={record[1]} HCHO={record[2]} CO={record[3]} VOC={record[4]} CO2={record[5]}")
                inside_block = False
                block_lines = []
                continue
            elif inside_block:
                block_lines.append(raw)

        except Exception as e:
            add_log(f"串口异常: {str(e)}")
            break

